"""make_results_package.py -- aggregate results/{e1,fmatch,ablation,e3,gamma}/*.json, results/e2_exp_g9.json, results/e4_noise.json
into tables (markdown + csv) and figures (pdf) under ../paper/results_package/.  Robust to missing pieces."""
import os, sys, glob, json, math, collections
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, '..', 'paper', 'results_package'); FIG = os.path.join(OUT, 'figures')
os.makedirs(FIG, exist_ok=True)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..', 'chatgpt_pro_job', 'inputs'))
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
plt.rcParams.update({'font.size': 10, 'axes.linewidth': 0.6, 'lines.linewidth': 1.3, 'figure.dpi': 150, 'pdf.fonttype': 42, 'legend.fontsize': 8, 'axes.labelsize': 10, 'xtick.labelsize': 9, 'ytick.labelsize': 9})
COL = {'vqc': 'tab:red', 'mlp': 'tab:blue', 'ff': 'tab:green', 'mlpref': 'k'}
LAB = {'vqc': 'QPINN (VQC)', 'mlp': 'MLP-matched', 'ff': 'FF-matched', 'mlpref': 'MLP-ref'}

def load(pattern):
    rows = []
    for f in sorted(glob.glob(os.path.join(HERE, pattern))):
        try: rows.append(json.load(open(f)))
        except Exception as e: print('skip', f, e)
    return rows

def msd(v):
    v = np.asarray(v, float); return (v.mean(), v.std(ddof=1) if len(v) > 1 else 0.0, len(v))

lines = ["# Results package (auto-generated by make_results_package.py)\n"]
# ---------------- E1
e1 = load('results/e1/*.json')
if e1:
    lines.append("## E1: parity at matched parameter count (physics-only, gamma = 9, five seeds)\n")
    lines.append("| case | model | config | params | lr | T relL2 mean +- sd | sigma relL2 mean +- sd | best-seed sigma | train s |\n|---|---|---|---|---|---|---|---|---|")
    groups = collections.defaultdict(list)
    for r in e1: groups[(r['case'], r['model'], r['n_q'], r['L'])].append(r)
    csv = ["case,model,n_q,L,params,lr,T_mean,T_sd,sigma_mean,sigma_sd,n_seeds,sigma_best,train_s_mean"]
    for key in sorted(groups, key=lambda k: (k[0], k[2] * 10 + k[3], k[1])):
        rs = groups[key]; cfg = 'q%dL%d' % (key[2], key[3]) if key[1] != 'mlpref' else '-'
        Tm, Ts, n = msd([r['relL2_T'] for r in rs]); Sm, Ss, _ = msd([r['relL2_sigma'] for r in rs])
        lines.append("| %s | %s | %s | %d | %g | %.4f +- %.4f | %.4f +- %.4f | %.4f | %.0f |" % (key[0], LAB[key[1]], cfg, rs[0]['n_params'], rs[0]['lr'], Tm, Ts, Sm, Ss, min(r['relL2_sigma'] for r in rs), np.mean([r['train_s'] for r in rs])))
        csv.append("%s,%s,%d,%d,%d,%g,%.6f,%.6f,%.6f,%.6f,%d,%.6f,%.1f" % (key[0], key[1], key[2], key[3], rs[0]['n_params'], rs[0]['lr'], Tm, Ts, Sm, Ss, n, min(r['relL2_sigma'] for r in rs), np.mean([r['train_s'] for r in rs])))
    open(os.path.join(OUT, 'table_e1.csv'), 'w').write('\n'.join(csv) + '\n')
    # figure: bar chart sigma error per case/model
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2))
    for ax, field in zip(axes, ['relL2_T', 'relL2_sigma']):
        cases = ['exp', 'step', 'smooth']; keys = [('vqc', 6, 4), ('mlp', 6, 4), ('ff', 6, 4), ('vqc', 4, 2), ('mlp', 4, 2), ('ff', 4, 2), ('mlpref', 6, 4)]
        w = 0.11
        for j, (mdl, nq, L) in enumerate(keys):
            ms = []; ss = []
            for c in cases:
                rs = groups.get((c, mdl, nq, L), []); m, s, _ = msd([r[field] for r in rs]) if rs else (np.nan, 0, 0); ms.append(m); ss.append(s)
            hatch = '' if (L == 4 or mdl == 'mlpref') else '////'
            ax.bar(np.arange(3) + (j - 3) * w, ms, w, yerr=ss, color=COL[mdl], edgecolor='k', linewidth=0.4, hatch=hatch,
                   label='%s %s' % (LAB[mdl], ('q%dL%d' % (nq, L)) if mdl != 'mlpref' else ''), capsize=1.5, error_kw=dict(lw=0.6))
        ax.set_xticks(range(3)); ax.set_xticklabels(cases); ax.set_yscale('log'); ax.set_ylabel('relative L2 error, ' + ('T' if field == 'relL2_T' else r'$\sigma$'))
    h, l = axes[1].get_legend_handles_labels(); fig.legend(h, l, fontsize=8, ncol=4, frameon=False, loc='lower center', bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.12, 1, 1)); fig.savefig(os.path.join(FIG, 'fig_e1_errors.pdf'), bbox_inches='tight'); plt.close(fig)
